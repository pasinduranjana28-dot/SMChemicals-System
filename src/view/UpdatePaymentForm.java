    private void updateBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBTNActionPerformed
        // TODO add your handling code here:
          if (paymentIDCMB.getSelectedIndex() <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please select a Payment ID.");
        return;
    }

        if (invoiceCMB.getSelectedIndex() <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please select an Invoice ID.");
            return;
        }

        String date = paymentDateTF.getText().trim();
        String amountText = amountTF.getText().trim();

        if (date.isEmpty() || amountText.isEmpty()
                || paymentMethodCMB.getSelectedIndex() <= 0
                || paymentStatusCMB.getSelectedIndex() <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Please fill in all fields.");
            return;
        }

        try {
            int paymentId = Integer.parseInt(
                    paymentIDCMB.getSelectedItem().toString());

            int invoiceId = Integer.parseInt(
                    invoiceCMB.getSelectedItem().toString());

            java.sql.Date paymentDate =
                    java.sql.Date.valueOf(date);

            double amount = Double.parseDouble(amountText);

            if (amount <= 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Amount must be greater than zero.");
                return;
            }

            entity.Payment payment = new entity.Payment();
            payment.setPaymentId(paymentId);
            payment.setInvoiceId(invoiceId);
            payment.setPaymentDate(paymentDate);
            payment.setAmount(amount);
            payment.setPaymentMethod(
                    paymentMethodCMB.getSelectedItem().toString());
            payment.setPaymentStatus(
                    paymentStatusCMB.getSelectedItem().toString());

            if (paymentDAO.updatePayment(payment)) {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Payment updated successfully!");

            if (paymentForm != null) {
                paymentForm.refreshPaymentTable();
            }

            loadPaymentIDs();

            paymentIDCMB.setSelectedIndex(0);
            invoiceCMB.setSelectedIndex(0);
            paymentDateTF.setText("");
            amountTF.setText("");
            paymentMethodCMB.setSelectedIndex(0);
            paymentStatusCMB.setSelectedIndex(0);
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Failed to update payment.");
            }

        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Enter a valid date (YYYY-MM-DD) and amount.");
        }
    }//GEN-LAST:event_updateBTNActionPerformed

