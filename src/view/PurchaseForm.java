        private void loadPurchases() {

        dao.PurchaseDAO dao = new dao.PurchaseDAO();

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) purchaseTable.getModel();

        model.setRowCount(0);

        String sql =
                "SELECT pu.purchase_id, "
              + "s.supplier_name, "
              + "p.product_name, "
              + "pi.quantity, "
              + "pi.unit_price, "
              + "pu.purchase_date, "
              + "pu.total_amount "
              + "FROM purchases pu "
              + "INNER JOIN suppliers s "
              + "ON pu.supplier_id = s.supplier_id "
              + "INNER JOIN purchase_items pi "
              + "ON pu.purchase_id = pi.purchase_id "
              + "INNER JOIN products p "
              + "ON pi.product_id = p.product_id "
              + "ORDER BY pu.purchase_id DESC";

        try (java.sql.Connection con =
                     database.DBConnection.getConnection();
             java.sql.PreparedStatement pst =
                     con.prepareStatement(sql);
             java.sql.ResultSet rs =
                     pst.executeQuery()) {

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("purchase_id"),
                    rs.getString("supplier_name"),
                    rs.getString("product_name"),
                    rs.getInt("quantity"),
                    rs.getDouble("unit_price"),
                    rs.getDate("purchase_date"),
                    rs.getDouble("total_amount")
                });
            }

        } catch (java.sql.SQLException e) {

            e.printStackTrace();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to load purchases."
            );
        }
    }
