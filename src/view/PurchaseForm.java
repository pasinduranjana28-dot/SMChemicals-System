    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        String idText = purchaseIDTF.getText().trim();

        if (idText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select a purchase from the table."
            );
            return;
        }

        int purchaseId;

        try {
            purchaseId = Integer.parseInt(idText);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Invalid purchase ID."
            );
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this purchase?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        dao.PurchaseDAO dao = new dao.PurchaseDAO();

        if (dao.deletePurchase(purchaseId)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Purchase deleted successfully."
            );

            supplierCMB.setSelectedIndex(0);
            productCMB.setSelectedIndex(0);
            quantityTF.setText("");
            unitPriceTF.setText("");
            totalAmountTF.setText("");
            purchaseIDTF.setText("");

            loadPurchases();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to delete purchase."
            );
        }
    }//GEN-LAST:event_deleteBTNActionPerformed

    private void productCMBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_productCMBActionPerformed
        // TODO add your handling code here:
            int selectedIndex = productCMB.getSelectedIndex();

        if (selectedIndex <= 0) {
            unitPriceTF.setText("");
            totalAmountTF.setText("");
            return;
        }

        int productId =
                (int) productMap.keySet().toArray()[selectedIndex - 1];

        dao.PurchaseDAO dao = new dao.PurchaseDAO();

        double price = dao.getProductPrice(productId);

        unitPriceTF.setText(String.valueOf(price));

        calculateTotal();
    }//GEN-LAST:event_productCMBActionPerformed

