        private void loadInvoices() {

        PaymentDAO dao = new PaymentDAO();

        invoiceMap = dao.getInvoiceList();

        invoiceCMB.removeAllItems();
        invoiceCMB.addItem("Select Invoice");

        for (Integer invoiceId : invoiceMap.keySet()) {
            invoiceCMB.addItem(String.valueOf(invoiceId));
        }
    }
        
        private void loadPayments() {

        PaymentDAO dao = new PaymentDAO();

        java.util.List<Payment> paymentList =
                dao.getAllPayments();

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        for (Payment payment : paymentList) {

            model.addRow(new Object[]{
                payment.getPaymentId(),
                payment.getInvoiceId(),
                payment.getPaymentDate(),
                payment.getAmount(),
                payment.getPaymentMethod(),
                payment.getPaymentStatus()
            });
        }
    }
        
    

