    private void loadSuppliers() {

    dao.SupplierDAO dao = new dao.SupplierDAO();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) supplierTable.getModel();

    model.setRowCount(0);

    for (entity.Supplier supplier : dao.getAllSuppliers()) {

        model.addRow(new Object[]{
            supplier.getSupplierId(),
            supplier.getSupplierName(),
            supplier.getPhone(),
            supplier.getEmail(),
            supplier.getAddress()
        });
    }
}

