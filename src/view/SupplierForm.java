    private void addBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBTNActionPerformed
        // TODO add your handling code here:
        String name = supplierNameTF.getText().trim();
        String phone = phoneTF.getText().trim();
        String email = emailTF.getText().trim();
        String address = addressTA.getText().trim();

        if (name.isEmpty() || phone.isEmpty()
                || email.isEmpty() || address.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please fill all supplier fields."
            );
            return;
        }

        entity.Supplier supplier = new entity.Supplier(
                name,
                phone,
                email,
                address
        );

        dao.SupplierDAO dao = new dao.SupplierDAO();

        if (dao.addSupplier(supplier)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Supplier added successfully."
            );

            supplierNameTF.setText("");
            phoneTF.setText("");
            emailTF.setText("");
            addressTA.setText("");

            loadSuppliers();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to add supplier."
            );
        }

    }//GEN-LAST:event_addBTNActionPerformed

    private void updateBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBTNActionPerformed
        // TODO add your handling code here:
        String idText = supplierIDTF.getText().trim();
    String name = supplierNameTF.getText().trim();
    String phone = phoneTF.getText().trim();
    String email = emailTF.getText().trim();
    String address = addressTA.getText().trim();

    if (idText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a supplier from the table."
        );
        return;
    }

    if (name.isEmpty() || phone.isEmpty()
            || email.isEmpty() || address.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please fill all supplier fields."
        );
        return;
    }

    int supplierId;

    try {
        supplierId = Integer.parseInt(idText);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Invalid supplier ID."
        );
        return;
    }

    entity.Supplier supplier = new entity.Supplier(
            supplierId,
            name,
            phone,
            email,
            address
    );

    dao.SupplierDAO dao = new dao.SupplierDAO();

    if (dao.updateSupplier(supplier)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier updated successfully."
        );

        supplierNameTF.setText("");
        phoneTF.setText("");
        emailTF.setText("");
        addressTA.setText("");

        loadSuppliers();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to update supplier."
        );
    }
    }//GEN-LAST:event_updateBTNActionPerformed

    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        String idText = supplierIDTF.getText().trim();

    if (idText.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a supplier from the table."
        );
        return;
    }

    int supplierId;

    try {
        supplierId = Integer.parseInt(idText);
    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Invalid supplier ID."
        );
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this supplier?",
            "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirm != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    dao.SupplierDAO dao = new dao.SupplierDAO();

    if (dao.deleteSupplier(supplierId)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Supplier deleted successfully."
        );

        supplierIDTF.setText("");
        supplierNameTF.setText("");
        phoneTF.setText("");
        emailTF.setText("");
        addressTA.setText("");

        loadSuppliers();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to delete supplier."
        );
    }
    }//GEN-LAST:event_deleteBTNActionPerformed

