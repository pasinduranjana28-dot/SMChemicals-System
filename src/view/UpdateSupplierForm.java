    private void supplierIDCMBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_supplierIDCMBActionPerformed
        // TODO add your handling code here:
        if (supplierIDCMB.getSelectedIndex() <= 0) {
        clearFields();
        return;
    }

        int supplierId = Integer.parseInt(
                supplierIDCMB.getSelectedItem().toString()
        );

        Supplier supplier =
                supplierDAO.getSupplierById(supplierId);

        if (supplier != null) {

            supplierNameTF.setText(
                    supplier.getSupplierName()
            );

            phoneTF.setText(
                    supplier.getPhone()
            );

            emailTF.setText(
                    supplier.getEmail()
            );

            addressTA.setText(
                    supplier.getAddress()
            );
        }
    }//GEN-LAST:event_supplierIDCMBActionPerformed

    private void updateBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBTNActionPerformed
        // TODO add your handling code here:
         if (supplierIDCMB.getSelectedIndex() <= 0) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a supplier."
        );

        return;
    }

        String name = supplierNameTF.getText().trim();
        String phone = phoneTF.getText().trim();
        String email = emailTF.getText().trim();
        String address = addressTA.getText().trim();

        if (name.isEmpty() ||
            phone.isEmpty() ||
            email.isEmpty() ||
            address.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please fill all supplier fields."
            );

            return;
        }

        int supplierId = Integer.parseInt(
                supplierIDCMB.getSelectedItem().toString()
        );

        Supplier supplier = new Supplier(
                supplierId,
                name,
                phone,
                email,
                address
        );

        if (supplierDAO.updateSupplier(supplier)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Supplier updated successfully!"
            );

            if (supplierForm != null) {
                supplierForm.refreshSupplierTable();
            }

            loadSupplierIDs();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to update supplier."
            );
        }
    }//GEN-LAST:event_updateBTNActionPerformed

