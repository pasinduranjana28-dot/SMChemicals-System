    private void stockOutBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_stockOutBTNActionPerformed
        // TODO add your handling code here:
        int selectedIndex = productCMB.getSelectedIndex();

    if (selectedIndex == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select a product.");
        return;
    }

    int productId = (int) productMap.keySet().toArray()[selectedIndex - 1];

    String quantityText = quantityTF.getText().trim();

    if (quantityText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter quantity.");
        return;
    }

    int quantity;

    try {
        quantity = Integer.parseInt(quantityText);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Quantity must be a valid number.");
        return;
    }

    if (quantity <= 0) {
        JOptionPane.showMessageDialog(this,
                "Quantity must be greater than 0.");
        return;
    }

    InventoryDAO dao = new InventoryDAO();

    if (dao.stockOut(productId, quantity)) {

        JOptionPane.showMessageDialog(this,
                "Stock removed successfully.");

        clearFields();
        loadInventory();

    } else {

        JOptionPane.showMessageDialog(this,
                "Failed to remove stock.\n"
                + "Check whether enough stock is available.");
    }
    }//GEN-LAST:event_stockOutBTNActionPerformed

    private void lowStockBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_lowStockBTNActionPerformed
        // TODO add your handling code here:
       InventoryDAO dao = new InventoryDAO();

        String sql = "SELECT p.product_name, i.quantity, i.reorder_level "
                   + "FROM inventory i "
                   + "INNER JOIN products p "
                   + "ON i.product_id = p.product_id "
                   + "WHERE i.quantity <= i.reorder_level";

        StringBuilder message = new StringBuilder();

        try (java.sql.Connection con =
                    database.DBConnection.getConnection();
             java.sql.PreparedStatement pst =
                    con.prepareStatement(sql);
             java.sql.ResultSet rs =
                    pst.executeQuery()) {

            while (rs.next()) {

                message.append("Product: ")
                       .append(rs.getString("product_name"))
                       .append(" | Quantity: ")
                       .append(rs.getInt("quantity"))
                       .append(" | Reorder Level: ")
                       .append(rs.getInt("reorder_level"))
                       .append("\n");
            }

            if (message.length() == 0) {

                JOptionPane.showMessageDialog(this,
                        "No low stock products.");

            } else {

                JOptionPane.showMessageDialog(this,
                        "Low Stock Products:\n\n"
                        + message.toString());
            }

        } catch (java.sql.SQLException e) {

            e.printStackTrace();

            JOptionPane.showMessageDialog(this,
                    "Failed to check low stock.");
        }
    }//GEN-LAST:event_lowStockBTNActionPerformed


