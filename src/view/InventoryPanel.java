    private void stockInBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_stockInBTNActionPerformed
        // TODO add your handling code here:
        int selectedIndex = productCMB.getSelectedIndex();

        if (selectedIndex == 0) {
            JOptionPane.showMessageDialog(this,
                    "Please select a product.");
            return;
        }

        int productId = (int) productMap.keySet().toArray()[selectedIndex - 1];
        
        String quantityText = quantityTF.getText().trim();
        String reorderLevelText = reorderLevelTF.getText().trim();


        if (quantityText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter quantity.");
            return;
        }

        if (reorderLevelText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter reorder level.");
            return;
        }

        int quantity;
        int reorderLevel;

        try {
            quantity = Integer.parseInt(quantityText);
            reorderLevel = Integer.parseInt(reorderLevelText);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Please enter valid numbers.");
            return;
        }


        if (quantity <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Quantity must be greater than 0.");
            return;
        }

        if (reorderLevel < 0) {
            JOptionPane.showMessageDialog(this,
                    "Reorder level cannot be negative.");
            return;
        }

        Inventory inventory = new Inventory(
                productId,
                quantity,
                reorderLevel
        );

        InventoryDAO dao = new InventoryDAO();

        if (dao.stockIn(inventory)) {

            JOptionPane.showMessageDialog(this,
                    "Stock added successfully.");

            clearFields();
            loadInventory();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Failed to add stock.");
        }
    }//GEN-LAST:event_stockInBTNActionPerformed

