    private void customerIDCMBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_customerIDCMBActionPerformed
        // TODO add your handling code here:

        if (customerIDCMB.getSelectedIndex() <= 0) {
            return;
        }

        int customerId = Integer.parseInt(
                customerIDCMB.getSelectedItem().toString()
        );

        Customer customer =
                customerDAO.getCustomerById(customerId);

        if (customer != null) {

            customerNameTF.setText(
                    customer.getCustomerName()
            );

            phoneTF.setText(
                    customer.getPhone()
            );

            emailTF.setText(
                    customer.getEmail()
            );

            addressTF.setText(
                    customer.getAddress()
            );
        }
    }//GEN-LAST:event_customerIDCMBActionPerformed

    private void updateBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBTNActionPerformed
        // TODO add your handling code here:

    if (customerIDCMB.getSelectedIndex() <= 0) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a customer ID."
        );

        return;
    }

    if (customerNameTF.getText().trim().isEmpty()
            || phoneTF.getText().trim().isEmpty()
            || emailTF.getText().trim().isEmpty()
            || addressTF.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please fill all customer fields."
        );

        return;
    }

    int customerId = Integer.parseInt(
            customerIDCMB.getSelectedItem().toString()
    );

    Customer customer = new Customer();

    customer.setCustomerId(customerId);

    customer.setCustomerName(
            customerNameTF.getText().trim()
    );

    customer.setPhone(
            phoneTF.getText().trim()
    );

    customer.setEmail(
            emailTF.getText().trim()
    );

    customer.setAddress(
            addressTF.getText().trim()
    );

    if (customerDAO.updateCustomer(customer)) {

        JOptionPane.showMessageDialog(
                this,
                "Customer updated successfully!"
        );

        // Refresh the main Customer table
        customerPanel.refreshCustomerTable();

        loadCustomerIDs();

        clearFields();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Failed to update customer."
        );
    }
    }//GEN-LAST:event_updateBTNActionPerformed

