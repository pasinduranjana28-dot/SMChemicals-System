    private void updateBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBTNActionPerformed
        // TODO add your handling code here:
        if (invoiceIDCMB.getSelectedIndex() <= 0) {
        JOptionPane.showMessageDialog(this, "Please select an invoice.");
        return;
    }

        if (saleCMB.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(this, "Please select a sale.");
            return;
        }

        String dateText = invoiceDateTF.getText().trim();

        if (dateText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the invoice date.");
            return;
        }

        try {
            int invoiceId = Integer.parseInt(
                invoiceIDCMB.getSelectedItem().toString()
            );

            int saleId = Integer.parseInt(
                saleCMB.getSelectedItem().toString()
            );

            java.sql.Date invoiceDate = java.sql.Date.valueOf(dateText);
            double totalAmount = Double.parseDouble(totalAmountTF.getText().trim());

            if (totalAmount <= 0) {
                JOptionPane.showMessageDialog(this, "Total amount must be greater than zero.");
                return;
            }

            Invoice invoice = new Invoice();
            invoice.setInvoiceId(invoiceId);
            invoice.setSaleId(saleId);
            invoice.setInvoiceDate(invoiceDate);
            invoice.setTotalAmount(totalAmount);

            if (invoiceDAO.updateInvoice(invoice)) {
                JOptionPane.showMessageDialog(this, "Invoice updated successfully.");

                if (invoiceForm != null) {
                    invoiceForm.refreshInvoiceTable();
                }

                clearFields();
                loadInvoiceIDs();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update invoice.");
            }

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                this, "Invalid date. Use YYYY-MM-DD."
            );
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_updateBTNActionPerformed

