        private void loadSales() {
            saleMap = invoiceDAO.getSaleList();

            saleCMB.removeAllItems();
            saleCMB.addItem("Select Sale");

            for (Integer saleId : saleMap.keySet()) {
                saleCMB.addItem(String.valueOf(saleId));
            }
        }

        private void loadInvoiceIDs() {
            invoiceIDCMB.removeAllItems();
            invoiceIDCMB.addItem("Select Invoice ID");

            for (Invoice invoice : invoiceDAO.getAllInvoices()) {
                invoiceIDCMB.addItem(String.valueOf(invoice.getInvoiceId()));
            }
        }

        private void loadSelectedInvoice() {
            if (invoiceIDCMB.getSelectedIndex() <= 0) {
                clearFields();
                return;
            }

            int invoiceId = Integer.parseInt(
                invoiceIDCMB.getSelectedItem().toString()
            );

            for (Invoice invoice : invoiceDAO.getAllInvoices()) {
                if (invoice.getInvoiceId() == invoiceId) {
                    loadingInvoice = true;

                    saleCMB.setSelectedItem(
                        String.valueOf(invoice.getSaleId())
                    );

                    invoiceDateTF.setText(
                        invoice.getInvoiceDate().toString()
                    );

                    totalAmountTF.setText(
                        String.format("%.2f", invoice.getTotalAmount())
                    );

                    loadingInvoice = false;
                    return;
                }
            }
        }

        private void clearFields() {
            loadingInvoice = true;

            if (invoiceIDCMB.getItemCount() > 0) {
                invoiceIDCMB.setSelectedIndex(0);
            }

            if (saleCMB.getItemCount() > 0) {
                saleCMB.setSelectedIndex(0);
            }

            invoiceDateTF.setText("");
            totalAmountTF.setText("");

            loadingInvoice = false;
        }

        private void updateTotalFromSale() {
            if (loadingInvoice) {
                return;
            }

            if (saleCMB.getSelectedIndex() <= 0) {
                totalAmountTF.setText("");
                return;
            }

            int saleId = Integer.parseInt(
                saleCMB.getSelectedItem().toString()
            );

            Double amount = saleMap.get(saleId);

            if (amount != null) {
                totalAmountTF.setText(String.format("%.2f", amount));
            }
        }



