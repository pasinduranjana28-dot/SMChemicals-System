    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        
        if (customerIDCMB.getSelectedIndex() <= 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a customer ID."
            );

            return;
        }

        int customerId = Integer.parseInt(
                customerIDCMB.getSelectedItem().toString()
        );

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this customer?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {

            if (customerDAO.deleteCustomer(customerId)) {

                JOptionPane.showMessageDialog(
                        this,
                        "Customer deleted successfully!"
                );

                // Refresh the main Customer table
                customerPanel.refreshCustomerTable();

                // Refresh IDs in this form
                loadCustomerIDs();

                customerIDCMB.setSelectedIndex(0);

                customerNameTF.setText("");
                phoneTF.setText("");
                emailTF.setText("");
                addressTF.setText("");

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Failed to delete customer."
                );
            }
        }
    }//GEN-LAST:event_deleteBTNActionPerformed

