    private void customerIDCMBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_customerIDCMBActionPerformed
        // TODO add your handling code here:
         if (customerIDCMB.getSelectedIndex() <= 0) {
        return;
        }

        int customerId = Integer.parseInt(
                customerIDCMB.getSelectedItem().toString()
        );

        Customer customer =
                customerDAO.getCustomerById(customerId);

        if (customer != null) {

            customerNameTF.setText(
                    customer.getCustomerName()
            );

            phoneTF.setText(
                    customer.getPhone()
            );

            emailTF.setText(
                    customer.getEmail()
            );

            addressTF.setText(
                    customer.getAddress()
            );
        }
    }//GEN-LAST:event_customerIDCMBActionPerformed

