    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        if (purchaseIDCMB.getSelectedIndex() <= 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a purchase."
        );
        return;
    }

        int purchaseId = Integer.parseInt(
                purchaseIDCMB.getSelectedItem().toString()
        );

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this purchase?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        if (purchaseDAO.deletePurchase(purchaseId)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Purchase deleted successfully!"
            );

            if (purchaseForm != null) {
                purchaseForm.refreshPurchaseTable();
            }

            loadPurchaseIDs();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to delete purchase. Check whether it is linked to other records."
            );
        }
    }//GEN-LAST:event_deleteBTNActionPerformed

