        private void loadSales() {

        InvoiceDAO dao = new InvoiceDAO();

        saleMap = dao.getSaleList();

        saleCMB.removeAllItems();
        saleCMB.addItem("Select Sale");

        for (Integer saleId : saleMap.keySet()) {
            saleCMB.addItem(String.valueOf(saleId));
        }
    }
        
        private void clearInvoiceForm() {

        invoiceIDTF.setText("");
        saleCMB.setSelectedIndex(0);
        invoiceDateTF.setText("");
        totalAmountTF.setText("");
    }
        
        private void loadInvoices() {

        InvoiceDAO dao = new InvoiceDAO();

        java.util.List<entity.Invoice> invoiceList =
                dao.getAllInvoices();

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) invoiceTable.getModel();

        model.setRowCount(0);

        for (entity.Invoice invoice : invoiceList) {

            model.addRow(new Object[]{
                invoice.getInvoiceId(),
                invoice.getSaleId(),
                invoice.getInvoiceDate(),
                invoice.getTotalAmount()
            });
        }
    }

