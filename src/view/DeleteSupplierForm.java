    private void supplierIDCMBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_supplierIDCMBActionPerformed
        // TODO add your handling code here:
         if (supplierIDCMB.getSelectedIndex() <= 0) {
        clearFields();
        return;
    }

        int supplierId = Integer.parseInt(
                supplierIDCMB.getSelectedItem().toString()
        );

        Supplier supplier =
                supplierDAO.getSupplierById(supplierId);

        if (supplier != null) {

            supplierNameTF.setText(
                    supplier.getSupplierName()
            );

            phoneTF.setText(
                    supplier.getPhone()
            );

            emailTF.setText(
                    supplier.getEmail()
            );

            addressTA.setText(
                    supplier.getAddress()
            );
        }
    }//GEN-LAST:event_supplierIDCMBActionPerformed

    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        if (supplierIDCMB.getSelectedIndex() <= 0) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a supplier."
        );

        return;
    }

        int supplierId = Integer.parseInt(
                supplierIDCMB.getSelectedItem().toString()
        );

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this supplier?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        if (supplierDAO.deleteSupplier(supplierId)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Supplier deleted successfully!"
            );

            if (supplierForm != null) {
                supplierForm.refreshSupplierTable();
            }

            loadSupplierIDs();
            clearFields();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to delete supplier."
            );
        }
    }//GEN-LAST:event_deleteBTNActionPerformed

