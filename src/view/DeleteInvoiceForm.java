        private void loadInvoiceIDs() {
            invoiceIDCMB.removeAllItems();
            invoiceIDCMB.addItem("Select Invoice ID");

            for (Invoice invoice : invoiceDAO.getAllInvoices()) {
                invoiceIDCMB.addItem(
                    String.valueOf(invoice.getInvoiceId())
                );
            }
        }

        private void loadSelectedInvoice() {
            if (invoiceIDCMB.getSelectedIndex() <= 0) {
                saleCMB.removeAllItems();
                invoiceDateTF.setText("");
                totalAmountTF.setText("");
                return;
            }

            int invoiceId = Integer.parseInt(
                invoiceIDCMB.getSelectedItem().toString()
            );

            for (Invoice invoice : invoiceDAO.getAllInvoices()) {
                if (invoice.getInvoiceId() == invoiceId) {
                    saleCMB.removeAllItems();
                    saleCMB.addItem(
                        String.valueOf(invoice.getSaleId())
                    );

                    invoiceDateTF.setText(
                        invoice.getInvoiceDate().toString()
                    );

                    totalAmountTF.setText(
                        String.valueOf(invoice.getTotalAmount())
                    );
                    return;
                }
            }
        }

        private void clearFields() {
            invoiceIDCMB.setSelectedIndex(0);
            saleCMB.removeAllItems();
            invoiceDateTF.setText("");
            totalAmountTF.setText("");
        }


