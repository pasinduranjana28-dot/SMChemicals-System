    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        
        if (invoiceIDCMB.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(
                this, "Please select an invoice ID."
            );
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this invoice?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int invoiceId = Integer.parseInt(
                invoiceIDCMB.getSelectedItem().toString()
            );

            if (invoiceDAO.deleteInvoice(invoiceId)) {
                JOptionPane.showMessageDialog(
                    this, "Invoice deleted successfully."
                );

                if (invoiceForm != null) {
                    invoiceForm.refreshInvoiceTable();
                }

                loadInvoiceIDs();
                clearFields();

            } else {
                JOptionPane.showMessageDialog(
                    this, "Failed to delete invoice."
                );
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                this, "Error deleting invoice: " + e.getMessage()
            );
            e.printStackTrace();
        }
    }//GEN-LAST:event_deleteBTNActionPerformed

