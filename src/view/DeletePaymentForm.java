        private void loadInvoices() {
        invoiceCMB.removeAllItems();
        invoiceCMB.addItem("Select Invoice");

        java.util.Map<Integer, Double> invoiceMap =
                paymentDAO.getInvoiceList();

        for (Integer invoiceId : invoiceMap.keySet()) {
            invoiceCMB.addItem(String.valueOf(invoiceId));
        }
    }

    private void loadPaymentIDs() {
        paymentIDCMB.removeAllItems();
        paymentIDCMB.addItem("Select Payment ID");

        java.util.List<entity.Payment> payments =
                paymentDAO.getAllPayments();

        for (entity.Payment payment : payments) {
            paymentIDCMB.addItem(
                    String.valueOf(payment.getPaymentId()));
        }
    }
    
    
        private void loadSelectedPayment() {
            Object selected = paymentIDCMB.getSelectedItem();

            if (selected == null ||
                    selected.toString().equals("Select Payment ID")) {
                clearFields();
                return;
            }

            int paymentId = Integer.parseInt(selected.toString());

            for (Payment payment : paymentDAO.getAllPayments()) {
                if (payment.getPaymentId() == paymentId) {

                    invoiceCMB.removeAllItems();
                    invoiceCMB.addItem(
                            String.valueOf(payment.getInvoiceId()));

                    paymentDateTF.setText(
                            payment.getPaymentDate() == null
                                    ? ""
                                    : payment.getPaymentDate().toString());

                    amountTF.setText(
                            String.valueOf(payment.getAmount()));

                    paymentMethodCMB.removeAllItems();
                    paymentMethodCMB.addItem(payment.getPaymentMethod());

                    paymentStatusCMB.removeAllItems();
                    paymentStatusCMB.addItem(payment.getPaymentStatus());

                    return;
                }
            }
        }

        private void clearFields() {
            invoiceCMB.removeAllItems();
            invoiceCMB.addItem("Select Invoice");

            paymentDateTF.setText("");
            amountTF.setText("");

            paymentMethodCMB.removeAllItems();
            paymentMethodCMB.addItem("Select Method");

            paymentStatusCMB.removeAllItems();
            paymentStatusCMB.addItem("Select Status");
        }


