    private void deleteBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBTNActionPerformed
        // TODO add your handling code here:
        if (paymentIDCMB.getSelectedIndex() <= 0) {
        JOptionPane.showMessageDialog(
                this, "Please select a Payment ID.");
        return;
    }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this payment?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        int paymentId = Integer.parseInt(
                paymentIDCMB.getSelectedItem().toString());

        if (paymentDAO.deletePayment(paymentId)) {
            JOptionPane.showMessageDialog(
                    this, "Payment deleted successfully!");

            if (paymentForm != null) {
                paymentForm.refreshPaymentTable();
            }

            loadPaymentIDs();
            paymentIDCMB.setSelectedIndex(0);
            clearFields();

        } else {
            JOptionPane.showMessageDialog(
                    this, "Failed to delete payment.");
        }
    }//GEN-LAST:event_deleteBTNActionPerformed

